/**
 * Image generation provider adapter interface
 */
export interface ImageProviderAdapter {
  /** Vendor identifier */
  provider: string

  /**
   * Builds the image generation request
   * @param config AI config { baseUrl, apiKey, model }
   * @param record image generation record
   */
  buildGenerateRequest(config: AIConfig, record: ImageGenerationRecord): ProviderRequest

  /**
   * Parses the generation response, deciding sync vs async
   */
  parseGenerateResponse(result: any): ImageGenResponse

  /**
   * Builds the polling request
   * @param config AI config
   * @param taskId task ID
   */
  buildPollRequest(config: AIConfig, taskId: string): ProviderRequest

  /**
   * Parses the polling response
   */
  parsePollResponse(result: any): ImagePollResponse

  /**
   * Extracts the image URL from the response (for direct download)
   * Returning null means the image data is base64 and must be handled via extractImageBase64
   */
  extractImageUrl(result: any): string | null

  /**
   * Extracts base64 image data from the response
   * Only for vendors that return base64 only, such as Gemini
   */
  extractImageBase64(result: any): { data: string; mimeType: string } | null
}

/**
 * Video generation provider adapter interface
 */
export interface VideoProviderAdapter {
  provider: string

  buildGenerateRequest(config: AIConfig, record: VideoGenerationRecord): ProviderRequest

  parseGenerateResponse(result: any): VideoGenResponse

  buildPollRequest(config: AIConfig, taskId: string): ProviderRequest

  parsePollResponse(result: any): VideoPollResponse

  extractVideoUrl(result: any): string | null

  /**
   * fusion-mlx #1254 handoff only: after a job completes, fetch the finished artifact via the
   * authenticated output endpoint (/v1/videos/jobs/{id}/output/{index}, FileResponse streamed mp4).
   * Implemented only by the fusion adapter; the host calls it when videoUrl is the 'job-output' placeholder.
   */
  buildJobOutputRequest?(config: AIConfig, taskId: string, index?: number): ProviderRequest
}

// ============ Shared types ============

export interface ProviderRequest {
  url: string
  method: string
  headers: Record<string, string>
  /**
   * For normal requests a JSON-serializable object (generation.ts does the JSON.stringify);
   * multipart uploads (e.g. OpenAI /v1/images/edits) return FormData directly —
   * in that case do not set Content-Type in headers; the boundary is generated by fetch.
   */
  body: any
}

export interface AIConfig {
  provider: string
  baseUrl: string
  apiKey: string
  model: string
}

export interface ImageGenerationRecord {
  id: number
  model?: string | null
  prompt?: string | null
  size?: string | null
  frameType?: string | null
  referenceImages?: string | null
  // ... other fields
}

